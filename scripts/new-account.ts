/**
 * Create a throwaway QoreChain *testnet* account (classical key + PQC recovery
 * code) and write it under .secrets/ plus a local .env. Prints only addresses.
 *
 *   pnpm account:new
 */
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { chmodSync } from "node:fs";
import path from "node:path";

import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { generatePqcRecoveryCode, unifiedAccountFromSeed, isValidRecoveryCode } from "@qorechain/sdk";

const root = path.resolve(import.meta.dirname, "..");
const secretsDir = path.join(root, ".secrets");
const envPath = path.join(root, ".env");

function bech32FromAccount(acc: { cosmos: string; evm: string }): { cosmos: string; evm: string } {
  return { cosmos: acc.cosmos, evm: acc.evm };
}

async function main(): Promise<void> {
  if (process.argv.includes("--force") === false && (existsSync(path.join(secretsDir, "private_key.txt")) || existsSync(envPath))) {
    console.error("An account already exists (.secrets/ or .env). Pass --force to replace it.");
    process.exitCode = 1;
    return;
  }

  const privateKey = generatePrivateKey();
  const recoveryCode = generatePqcRecoveryCode();
  if (!isValidRecoveryCode(recoveryCode)) {
    throw new Error("SDK produced an invalid recovery code; aborting.");
  }
  const acc = unifiedAccountFromSeed(Uint8Array.from(Buffer.from(privateKey.slice(2), "hex")), {
    recoveryCode,
  });
  const { cosmos, evm } = bech32FromAccount(acc);

  mkdirSync(secretsDir, { recursive: true, mode: 0o700 });
  const files: Record<string, string> = {
    "private_key.txt": privateKey + "\n",
    "recovery_code.txt": recoveryCode + "\n",
    "address.txt": cosmos + "\n",
    "evm_address.txt": evm + "\n",
    "README.txt":
      "TESTNET ONLY throwaway QoreChain account for QoreStamp.\n" +
      "Never send mainnet funds. Never commit these files.\n" +
      "private_key.txt and recovery_code.txt control the account together.\n",
  };
  for (const [name, body] of Object.entries(files)) {
    const p = path.join(secretsDir, name);
    writeFileSync(p, body, { encoding: "utf8", mode: 0o600 });
    chmodSync(p, 0o600);
  }
  chmodSync(secretsDir, 0o700);

  const env = `# TESTNET ONLY. Generated by pnpm account:new. Do not commit.
PRIVATE_KEY=${privateKey}
QORE_PQC_RECOVERY_CODE=${recoveryCode}
QORE_NETWORK=testnet
QORE_WINDOW_BLOCKS=600
QORE_WINDOW_TXS=5
`;
  writeFileSync(envPath, env, { encoding: "utf8", mode: 0o600 });
  chmodSync(envPath, 0o600);

  console.log("Wrote throwaway testnet account to .secrets/ and .env (both gitignored).");
  console.log(`account:  ${evm}  (${cosmos})`);
  console.log("Next: claim 100 test QOR at https://dashboard.qorechain.io/faucet with the qor1 address.");
  console.log("Then: pnpm window register && pnpm window open && pnpm deploy:testnet");
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
